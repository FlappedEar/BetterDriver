/**
 * A synthetic VBO for the import tests: a circle of 80 m radius around 45 N 0.5 W at 20 m/s (a lap
 * every 25.13 s) at 10 Hz from 10:42:00 UTC on 12 Oct 2026, starting 0.3 rad before the
 * start/finish line due north, so longitudes are west (positive in a VBO).
 */
internal object SyntheticCircle {
    const val DateLine = "File created on 12/10/2026 @ 10:42:00"

    const val centerLat = 45.0
    const val centerLon = -0.5
    const val radius = 80.0
    const val speed = 20.0
    const val lapSeconds = 2 * PI * radius / speed
    const val metresPerDegree = 111_320.0

    /** 2026-10-12T10:42:00Z. */
    const val start = 1_791_801_720_000L

    val track = Track(
        id = "circle",
        name = "Circle",
        center = GeoPoint(centerLat, centerLon),
        radiusMeters = 500.0,
        startFinish = TrackLine(
            GeoPoint(centerLat + (radius + 15) / metresPerDegree, centerLon),
            GeoPoint(centerLat + (radius - 15) / metresPerDegree, centerLon),
        ),
    )

    fun position(t: Double): Pair<Double, Double> {
        val angle = -0.3 + speed * t / radius
        val lat = centerLat + radius * cos(angle) / metresPerDegree
        val lon = centerLon + radius * sin(angle) / (metresPerDegree * cos(centerLat * PI / 180))
        return lat to lon
    }

    private fun two(n: Long) = n.toString().padStart(2, '0')

    /** Milliseconds of the day as hhmmss.ss. */
    private fun timeOfDay(ms: Long) =
        two(ms / 3_600_000) + two(ms / 60_000 % 60) + two(ms / 1_000 % 60) + "." + two(ms % 1_000 / 10)

    /** The synthetic VBO, [rows] rows at 10 Hz, its first date line [dateLine]. */
    fun vbo(rows: Int = 600, dateLine: String = DateLine): String {
        val sb = StringBuilder()
        sb.append("$dateLine\r\n\r\n[header]\r\nsatellites\r\ntime\r\nlatitude\r\nlongitude\r\n")
        sb.append("velocity kmh\r\nheading\r\nheight\r\nlateral acceleration g\r\n\r\n")
        sb.append("[comments]\r\nGenerated by Synthetic Logger 1.0\r\n\r\n")
        sb.append("[column names]\r\nsats time lat long velocity heading height latacc\r\n\r\n[data]\r\n")
        val startOfDay = 10 * 3_600_000L + 42 * 60_000L
        for (i in 0 until rows) {
            val t = i / 10.0
            val (lat, lon) = position(t)
            val heading = ((-0.3 + speed * t / radius) * 180 / PI + 90 + 360) % 360
            // 75: 11 satellites with Racelogic's DGPS flag (64).
            sb.append("075 ${timeOfDay(startOfDay + i * 100L)} ${lat * 60} ${-lon * 60} 72.000 $heading 82.0 -0.51\r\n")
        }
        return sb.toString()
    }
}

/**
 * The common import (FBBD-164, FBBD-331), as iOS runs it: the [SyntheticCircle] VBO read through
 * [Utf8Chars] and [LineReader] into the [ForeignSessionWriter], its files kept in memory and read
 * back as SessionStore.read does.
 */
class ForeignImportTest {
    private val track = SyntheticCircle.track
    private val start = SyntheticCircle.start
    private val lapSeconds = SyntheticCircle.lapSeconds

    private fun position(t: Double) = SyntheticCircle.position(t)

    private fun vbo(rows: Int = 600, dateLine: String = SyntheticCircle.DateLine) = SyntheticCircle.vbo(rows, dateLine)

    /** A session's files in memory, written as the stores write them. */
    private class MemoryFiles : ForeignSessionFiles {
        val chunks = ArrayList<ByteSink>()
        var meta: Map<String, String> = emptyMap()
        var finished: Map<String, String>? = null
        var aborted = false

        override fun create(info: SessionInfo): String {
            meta = metaEntries(Id, info)
            return Id
        }

        override fun open(channels: List<ChannelDef>) {
            chunks += ByteSink()
            channels.forEach { write(Record.Channel(it)) }
        }

        override fun write(record: Record) {
            chunks.last().write(Frames.encode(record))
        }

        override fun writeMeta(id: String, info: SessionInfo) {
            meta = metaEntries(id, info)
        }

        override fun close() = Unit

        override fun writeFinished(id: String, reason: String, endMicros: Long) {
            finished = mapOf("reason" to reason, "endMicros" to endMicros.toString())
        }

        override fun abort() {
            aborted = true
        }

        fun read(): SessionData {
            val bytes = chunks.asSequence().map { it.toByteArray() }
            return sessionDataOf(Id, metaFromEntries(meta), SessionState.FINISHED, bytes)
        }

        companion object {
            const val Id = "20261012-124200-0123abcd"
        }
    }

    /** Bytes handed out [piece] at a time, so characters and lines are split between reads. */
    private fun pieces(bytes: ByteArray, piece: Int): (ByteArray, Int, Int) -> Int {
        var at = 0
        return { buf, offset, length ->
            val n = minOf(piece, length, bytes.size - at)
            if (n <= 0) {
                -1
            } else {
                bytes.copyInto(buf, offset, at, at + n)
                at += n
                n
            }
        }
    }

    private fun import(
        text: String,
        files: MemoryFiles = MemoryFiles(),
        tracks: List<Track> = listOf(track),
        piece: Int = 4_093,
    ): ImportedSession {
        val bytes = text.encodeToByteArray()
        val format = checkNotNull(ForeignFormat.detect(bytes.copyOf(minOf(bytes.size, ForeignFormat.PeekBytes))))
        val writer = ForeignSessionWriter(files, ImportOrigin(format.label, "synthetic.vbo"), tracks, CircuitList.Empty)
        try {
            val chars = Utf8Chars(pieces(bytes, piece))
            readText(format, LineReader(chars::read), writer, FallbackDay)
            return writer.finish(format)
        } finally {
            writer.abort()
        }
    }

    private fun values(data: SessionData, channelId: Int) =
        data.sampleSets.mapNotNull { s -> s.values.firstOrNull { it.channelId == channelId }?.value }

    @Test
    fun `a synthetic VBO becomes a finished session with its samples`() {
        val files = MemoryFiles()
        val made = import(vbo(), files)
        assertEquals(ForeignFormat.VBO, made.format)
        assertEquals(600, made.points)
        assertEquals(0, made.skipped)
        assertEquals(59_900_000L, made.durationMicros)
        assertEquals(mapOf("reason" to "imported", "endMicros" to "59900000"), files.finished)

        val data = files.read()
        assertEquals(start, data.info.startUtcMillis)
        assertEquals("VBO", data.info.imported?.format)
        assertEquals("synthetic.vbo", data.info.imported?.fileName)
        assertEquals("Synthetic Logger 1.0", data.info.imported?.receiver)
        assertEquals(10.0, data.info.imported?.sampleRateHz)
        assertEquals(600, data.sampleSets.size)
        assertEquals(0L, data.sampleSets.first().tMicros)
        assertEquals(100_000L, data.sampleSets[1].tMicros)
        assertEquals(start.toDouble(), values(data, GnssChannels.UTC_MS.id).first())
        val (lat, lon) = position(0.0)
        assertEquals(lat, values(data, GnssChannels.LAT.id).first(), 1e-9)
        // Minutes, positive west, back to degrees east.
        assertEquals(lon, values(data, GnssChannels.LON.id).first(), 1e-9)
        assertTrue(values(data, GnssChannels.SPEED_KMH.id).all { abs(it - 72.0) < 1e-9 })
        assertTrue(values(data, GnssChannels.SATS.id).all { it == 11.0 })
        assertEquals(-0.51, values(data, ForeignImport.AccelLateral.id).first(), 1e-9)
        assertEquals(Provenance.MEASURED_GNSS_RECEIVER, data.channels.getValue(GnssChannels.SPEED_KMH.id).provenance)
        assertEquals("imported", data.end?.reason)
        assertEquals(59_900_000L, data.end?.tMicros)
    }

    @Test
    fun `the track is detected and laps are timed as on Android`() {
        val made = import(vbo())
        assertEquals(track.id, (made.detection as TrackDetection.Saved).track.id)
        val files = MemoryFiles()
        import(vbo(), files)
        val data = files.read()
        assertEquals("Circle", data.info.track)
        assertEquals(track.startFinish?.left?.lat, data.info.startFinish?.lat1)
        assertEquals(track.id, TrackEvent.savedTrackId(data.events))
        val laps = replayLaps(made.id, data.sampleSets, track)
        val timed = laps.laps.filter { it.lap.kind == LapKind.Timed }
        assertEquals(2, timed.size)
        timed.forEach { assertEquals(lapSeconds, it.lap.timeMicros / 1e6, 0.05) }
    }

    @Test
    fun `away from saved tracks the session has no track`() {
        val made = import(vbo(), tracks = emptyList())
        assertEquals(TrackDetection.Unknown, made.detection)
        assertEquals("", made.info.track)
        assertNull(made.info.startFinish)
    }

    @Test
    fun `every piece size reads the same file`() {
        val text = "﻿" + vbo(rows = 50).replace("Synthetic", "Synthétique ✓")
        val first = import(text, piece = 1)
        for (piece in listOf(2, 3, 7, 65_536)) {
            val made = import(text, piece = piece)
            assertEquals(first.points, made.points)
            assertEquals("Synthétique ✓ Logger 1.0", made.info.imported?.receiver)
        }
    }

    @Test
    fun `a VBO without a date line is put on the fallback day`() {
        val made = import(vbo(rows = 20, dateLine = "Racelogic export"))
        assertEquals(FallbackDay * 86_400_000L + start % 86_400_000L, made.info.startUtcMillis)
    }

    @Test
    fun `a file without positions is refused and the session dropped`() {
        val files = MemoryFiles()
        assertFailsWith<ImportFormatException> { import(vbo(rows = 1), files) }
        assertTrue(files.aborted)
        assertNull(files.finished)
    }

    @Test
    fun `dates count days as java time does`() {
        assertEquals(0L, epochDayOf(1970, 1, 1))
        assertEquals(11_016L, epochDayOf(2000, 2, 29))
        assertEquals(20_738L, epochDayOf(2026, 10, 12))
        assertEquals(-1L, epochDayOf(1969, 12, 31))
        assertNull(epochDayOf(2026, 2, 29))
        assertNull(epochDayOf(2026, 4, 31))
        assertNull(epochDayOf(2026, 13, 1))
        assertNull(epochDayOf(2026, 1, 0))
    }

    private companion object {
        /** 2026-10-11, a day before the file's own date. */
        const val FallbackDay = 20_737L
    }
}
