/**
 * BetterDriver's VBO export as FlappedEar Overlays reads it (Arek, 2026-10-13; Overlays KAN-259).
 * [OverlaysVbo] follows Overlays' VboParser (native/src/telemetry/VboParser.cpp): its sections,
 * its time column, its coordinate evidence (the exact `Generated by BetterDriver` comment, arc-minutes,
 * longitude west-positive), its timing gates and its channel aliases, first match by column order.
 * If the export stops meeting one of those, Overlays loses the map, the laps or the G gauges.
 */
class OverlaysExportTest {
    private val centerLat = 50.0
    private val centerLon = 19.0
    private val metersPerDegreeLat = 111_195.0
    private val metersPerDegreeLon = metersPerDegreeLat * cos(centerLat * PI / 180.0)
    private val radius = 200.0
    private val speed = 25.0 // m/s
    private val leftG = speed * speed / radius / 9.80665

    private val accelX = ChannelDef(110, "accel_x", "g", "racebox", 3)
    private val accelY = ChannelDef(111, "accel_y", "g", "racebox", 3)

    /** Three anticlockwise laps (left turns) of a 200 m circle at 25 Hz, from the south, at constant speed. */
    private fun circle(accelerometer: Boolean): SessionData {
        val steps = (2 * PI * radius / speed / 0.04).toInt()
        val sets = (0 until 3 * steps).map { i ->
            val angle = -PI / 2 + 2 * PI * i / steps
            val values = mutableListOf(
                ChannelValue(GnssChannels.LAT.id, centerLat + radius * sin(angle) / metersPerDegreeLat),
                ChannelValue(GnssChannels.LON.id, centerLon + radius * cos(angle) / metersPerDegreeLon),
                ChannelValue(GnssChannels.SPEED_KMH.id, speed * 3.6),
            )
            if (accelerometer) {
                // A receiver mounted backwards and tilted: its Y axis reads a left turn negative.
                values += ChannelValue(accelX.id, 0.04 * sin(i * 0.37))
                values += ChannelValue(accelY.id, -leftG + 0.05)
            }
            SampleSet(i * 40_000L, values)
        }
        val channels = GnssChannels.ALL + if (accelerometer) listOf(accelX, accelY) else emptyList()
        val gate = Gate(
            "Start",
            centerLat + (-radius + 15) / metersPerDegreeLat, centerLon,
            centerLat + (-radius - 15) / metersPerDegreeLat, centerLon,
        )
        val info = SessionInfo(
            startUtcMillis = 1_791_892_800_000L, // 2026-10-13 12:00:00 UTC
            track = "Test circle",
            devices = listOf("RaceBox Micro"),
            startFinish = gate,
            channels = channels,
        )
        return SessionData(
            "s", info, SessionState.FINISHED, channels.associateBy { it.id }, sets, emptyList(), null, 0, 0,
        )
    }

    private fun export(data: SessionData): OverlaysVbo {
        val out = ByteArrayOutputStream()
        VboExporter.export(data, out, derived = vboAccelerations(data))
        return OverlaysVbo(out.toString(Charsets.UTF_8))
    }

    @Test
    fun `Overlays knows the exporter, so it reads GPS in arc-minutes with west-positive longitude`() {
        val vbo = export(circle(accelerometer = true))
        assertEquals(listOf("Generated by BetterDriver"), vbo.exporters, "the comment Overlays recognises, alone")
        assertTrue(vbo.header.none { it.contains("coordinate units", ignoreCase = true) })
        assertTrue(vbo.created.matches(Regex("""File created on \d{2}/\d{2}/\d{4} @ \d{2}:\d{2}:\d{2}""")))
        assertEquals("File created on 13/10/2026 @ 12:00:00", vbo.created)
        val lat = vbo.column("lat")
        val lon = vbo.column("long")
        for (i in lat.indices) {
            val north = (lat[i] / 60.0 - centerLat) * metersPerDegreeLat
            val east = (-lon[i] / 60.0 - centerLon) * metersPerDegreeLon // west-positive
            assertEquals(radius, kotlin.math.hypot(north, east), 0.5, "row $i")
        }
    }

    @Test
    fun `the time column is UTC clock time Overlays parses and it always moves forward`() {
        val vbo = export(circle(accelerometer = false))
        assertEquals("time", vbo.names.first { OverlaysVbo.TimeName.matches(it) })
        val times = vbo.cells("time").map { assertNotNull(OverlaysVbo.clockSeconds(it), "time '$it'") }
        assertEquals(12 * 3600.0, times.first(), 1e-9)
        assertTrue(times.zipWithNext().all { (a, b) -> b > a })
    }

    @Test
    fun `the start gate is two endpoints Overlays converts back to the track's line`() {
        val data = circle(accelerometer = false)
        val vbo = export(data)
        val gate = vbo.gates.single()
        assertEquals("Start", gate[0])
        val c = gate.subList(1, 5).map { it.toDouble() } // long1 lat1 long2 lat2
        val expected = assertNotNull(data.info.startFinish)
        assertEquals(expected.lat1, c[1] / 60.0, 1e-7)
        assertEquals(expected.lon1, -c[0] / 60.0, 1e-7)
        assertEquals(expected.lat2, c[3] / 60.0, 1e-7)
        assertEquals(expected.lon2, -c[2] / 60.0, 1e-7)
    }

    @Test
    fun `Overlays finds the car's G, speed and position in the columns it looks for`() {
        val vbo = export(circle(accelerometer = true))
        val aliases = vbo.aliases()
        assertEquals("velocity", aliases["speed"])
        assertEquals("lat", aliases["latitude"])
        assertEquals("long", aliases["longitude"])
        assertEquals(VboLateralG, aliases["lateralAcceleration"])
        assertEquals(VboLongitudinalG, aliases["longitudinalAcceleration"])
        assertEquals(listOf("g", "g"), vbo.units(VboLongitudinalG, VboLateralG))
    }

    @Test
    fun `lateral G is positive in a left turn and longitudinal G about zero at constant speed`() {
        for (accelerometer in listOf(true, false)) {
            val vbo = export(circle(accelerometer))
            // Past the first second, where GPS-derived G has no history yet.
            val lateral = vbo.column(VboLateralG).drop(50)
            val longitudinal = vbo.column(VboLongitudinalG).drop(50)
            assertEquals(leftG, lateral.average(), 0.03, "accelerometer $accelerometer")
            assertTrue(abs(longitudinal.average()) < 0.05, "accelerometer $accelerometer: ${longitudinal.average()}")
        }
    }

    @Test
    fun `every row has a value in every column and nothing names RaceBox`() {
        val vbo = export(circle(accelerometer = true))
        assertTrue(vbo.rows.all { it.size == vbo.names.size })
        assertTrue(vbo.rows.flatten().all { it.toDoubleOrNull()?.isFinite() == true })
        assertTrue(!vbo.text.contains("racebox", ignoreCase = true))
    }
}

/**
 * A BetterDriver VBO read by the rules of FlappedEar Overlays' VboParser: sections by `[name]`, lines
 * starting `;` or `#` skipped, whitespace-separated columns, the `Generated by` comments, timing gate
 * lines `name long1 lat1 long2 lat2 [description]`, and the alias patterns its resolveAliases uses.
 */
private class OverlaysVbo(val text: String) {
    private val sections = LinkedHashMap<String, MutableList<String>>()

    init {
        var current = sections.getOrPut("") { mutableListOf() }
        for (raw in text.split("\r\n", "\n")) {
            val line = raw.trim()
            if (line.isEmpty() || line.startsWith(";") || line.startsWith("#")) continue
            val section = Regex("""^\[([^\]]+)\]$""").find(line)
            if (section != null) {
                current = sections.getOrPut(section.groupValues[1].trim().lowercase()) { mutableListOf() }
            } else {
                current += line
            }
        }
    }

    val created: String get() = sections.getValue("").single { it.startsWith("File created on ") }
    val header: List<String> get() = sections["header"].orEmpty()
    val exporters: List<String>
        get() = sections["comments"].orEmpty().filter { it.startsWith("Generated by ", ignoreCase = true) }.distinct()
    val gates: List<List<String>> get() = sections["laptiming"].orEmpty().map { it.split(Regex("\\s+")) }
    val names: List<String> get() = sections.getValue("column names").single().split(Regex("\\s+"))
    val rows: List<List<String>> get() = sections.getValue("data").map { it.split(Regex("\\s+")) }

    fun cells(name: String): List<String> {
        val i = names.indexOf(name)
        require(i >= 0) { "no column $name in $names" }
        return rows.map { it[i] }
    }

    fun column(name: String): List<Double> = cells(name).map { it.toDouble() }

    /** Units of custom columns: [channel units] lists one per [header] entry that is not a standard channel. */
    fun units(vararg columns: String): List<String> {
        val custom = header.filterNot { it in Standard }
        val units = sections["channel units"].orEmpty()
        return columns.map { units[custom.indexOf(it)] }
    }

    /** Overlays' alias for each channel kind: the first column by order that matches one of its patterns. */
    fun aliases(): Map<String, String> = AliasPatterns.mapNotNull { (alias, patterns) ->
        names.firstOrNull { name -> patterns.any { it.containsMatchIn(name) } }?.let { alias to it }
    }.toMap()

    companion object {
        val TimeName = Regex("^(?:time|timestamp|utc.?time)$", RegexOption.IGNORE_CASE)

        private val Standard = setOf(
            "satellites", "time", "latitude", "longitude", "velocity kmh", "heading", "height",
            "avifileindex", "avisynctime",
        )

        private fun p(pattern: String) = Regex(pattern, RegexOption.IGNORE_CASE)

        /** As in VboParser.cpp aliasPatterns. */
        private val AliasPatterns = listOf(
            "speed" to listOf(p("^velocity$"), p("^gps.?speed"), p("^speed$"), p("^obd.?speed")),
            "latitude" to listOf(p("^latitude$"), p("^lat$")),
            "longitude" to listOf(p("^longitude$"), p("^lon(?:g)?$")),
            "lateralAcceleration" to
                listOf(p("^latacc$"), p("lat(?:eral)?.?(?:accel|acceleration|g)"), p("^g.?x$")),
            "longitudinalAcceleration" to
                listOf(p("^longacc$"), p("long(?:itudinal)?.?(?:accel|acceleration|g)"), p("^g.?y$")),
        )

        /** Compact HHMMSS.sss clock time in seconds of day, as Overlays' parseTimestamp reads it. */
        fun clockSeconds(text: String): Double? {
            val m = Regex("""^(\d{2})(\d{2})(\d{2})(?:\.(\d+))?$""").find(text) ?: return null
            val (h, min, s) = m.destructured.toList().take(3).map { it.toInt() }
            val fraction = m.groupValues[4].takeIf { it.isNotEmpty() }?.let { "0.$it".toDouble() } ?: 0.0
            return if (h < 24 && min < 60 && s < 60) h * 3600.0 + min * 60.0 + s + fraction else null
        }
    }
}
