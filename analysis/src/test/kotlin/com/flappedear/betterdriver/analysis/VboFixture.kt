/**
 * Reads the VBO files of FlappedEar Telemetry's parity corpus the way Telemetry's parser does, for
 * the parity tests only: the coordinate unit from the header or the RaceChrono 10.2.4 exporter
 * line, timing gates (RaceChrono's centre-and-direction gates rebuilt across the direction),
 * clock or seconds timestamps rebased to the first row, and every value stored as float32, as
 * Telemetry stores it. Rows whose time is missing, repeated or going backwards are skipped.
 */
object VboFixture {
    fun read(name: String): TelemetrySession {
        val text = VboFixture::class.java.getResourceAsStream("/parity/corpus/$name")!!.readBytes().decodeToString()
        return parse(text)
    }

    fun parse(text: String): TelemetrySession {
        val sections = LinkedHashMap<String, MutableList<String>>()
        var section = ""
        sections[section] = mutableListOf()
        for (raw in text.removePrefix("﻿").split('\n')) {
            val line = raw.trim()
            if (line.isEmpty() || line.startsWith(";") || line.startsWith("#")) continue
            if (line.startsWith("[") && line.endsWith("]")) {
                section = line.substring(1, line.length - 1).trim().lowercase()
                sections.getOrPut(section) { mutableListOf() }
            } else {
                sections.getValue(section) += line
            }
        }
        val exporter = sections["comments"].orEmpty().lastOrNull { it.startsWith("Generated by ", ignoreCase = true) }
        val centreDirection = exporter.equals("Generated by RaceChrono Pro v10.2.4", ignoreCase = true)
        var arcMinutes = centreDirection
        for (entry in sections["header"].orEmpty()) {
            val sep = entry.indexOfFirst { it == ':' || it == '=' }
            if (sep < 0 || !entry.substring(0, sep).trim().equals("coordinate units", ignoreCase = true)) continue
            arcMinutes = entry.substring(sep + 1).trim().lowercase() == "arc-minutes"
        }
        fun degrees(value: Double, limit: Double): Double? {
            if (!value.isFinite()) return null
            val d = if (arcMinutes) value / 60.0 else value
            return if (abs(d) <= limit) d else null
        }

        val gates = sections["laptiming"].orEmpty().mapNotNull { gate(it, centreDirection, ::degrees) }

        val names = sections.entries.first { it.key.contains("column") }.value.single().trim().split(Regex("\\s+"))
        val rows = sections.entries.first { it.key.startsWith("data") }.value
        val timeIndex = names.indexOfFirst { it.matches(Regex("(?i)time|timestamp|utc.?time")) }
        val times = ArrayList<Double>()
        val columns = names.map { ArrayList<Double>() }
        var origin: Double? = null
        var previous: Double? = null
        for (row in rows) {
            val cells = row.trim().split(Regex("\\s+"))
            val absolute = cells.getOrNull(timeIndex)?.let(::timestamp) ?: continue
            if (origin == null) origin = absolute
            if (previous != null && absolute <= previous) continue
            previous = absolute
            times += absolute - origin
            names.forEachIndexed { c, columnName ->
                val parsed = cells.getOrNull(c)?.toDoubleOrNull()
                val axisLimit = when (columnName.lowercase()) {
                    "lat", "latitude" -> 90.0
                    "lon", "long", "longitude" -> 180.0
                    else -> null
                }
                val value = when {
                    parsed == null || !parsed.isFinite() -> Double.NaN
                    axisLimit != null -> degrees(parsed, axisLimit) ?: Double.NaN
                    else -> parsed
                }
                val stored = value.isFinite() && abs(value) <= Float.MAX_VALUE
                columns[c] += if (stored) value.toFloat().toDouble() else Double.NaN
            }
        }
        val timeArray = times.toDoubleArray()
        val channels = LinkedHashMap<String, TelemetryChannel>()
        names.forEachIndexed { c, columnName ->
            if (c == timeIndex) return@forEachIndexed
            val values = columns[c].toDoubleArray()
            if (values.any { it.isFinite() }) channels[columnName] = TelemetryChannel(columnName, timeArray, values)
        }
        val sorted = channels.keys.sortedWith(compareBy<String> { it.lowercase() }.thenBy { it })
        val aliases = HashMap<String, String>()
        fun alias(semantic: String, vararg patterns: String) {
            for (p in patterns) {
                val match = sorted.firstOrNull { it.matches(Regex(p, RegexOption.IGNORE_CASE)) }
                if (match != null) {
                    aliases[semantic] = match
                    return
                }
            }
        }
        alias(Aliases.SPEED, "velocity", "gps.?speed.*", "speed")
        alias(Aliases.LATITUDE, "latitude", "lat")
        alias(Aliases.LONGITUDE, "longitude", "lon(?:g)?")
        return TelemetrySession(channels, aliases, gates)
    }

    private fun timestamp(text: String): Double? {
        Regex("^(\\d{1,2}):(\\d{2}):(\\d{2}(?:\\.\\d+)?)$").find(text)?.let { m ->
            return m.groupValues[1].toInt() * 3600.0 + m.groupValues[2].toInt() * 60.0 + m.groupValues[3].toDouble()
        }
        Regex("^(\\d{2})(\\d{2})(\\d{2})(?:\\.(\\d+))?$").find(text)?.let { m ->
            val fraction = m.groupValues[4].let { if (it.isEmpty()) 0.0 else "0.$it".toDouble() }
            val (h, min, s) = m.destructured
            return h.toInt() * 3600.0 + min.toInt() * 60.0 + (s.toInt() + fraction)
        }
        return text.toDoubleOrNull()
    }

    private fun gate(line: String, centreDirection: Boolean, degrees: (Double, Double) -> Double?): TimingGate? {
        val tokens = line.trim().split(Regex("\\s+"), limit = 6)
        if (tokens.size < 5) return null
        val v = tokens.subList(1, 5).map { it.toDoubleOrNull() ?: return null }
        val lonA = degrees(v[0], 180.0) ?: return null
        val latA = degrees(v[1], 90.0) ?: return null
        val lonB = degrees(v[2], 180.0) ?: return null
        val latB = degrees(v[3], 90.0) ?: return null
        var a = GeoCoordinate(latA, lonA)
        var b = GeoCoordinate(latB, lonB)
        if (a == b) return null
        if (centreDirection) {
            val vector = projectCoordinate(b, a)
            val width = hypot(vector.eastMeters, vector.northMeters)
            if (abs(a.latitudeDegrees) >= 89.0 || width < 0.01 || width > 1000.0) return null
            val metersPerDegree = AnalysisEarthRadiusMeters * PI / 180.0
            val deltaLat = vector.eastMeters * .5 / metersPerDegree
            val deltaLon = -vector.northMeters * .5 / (metersPerDegree * cos(a.latitudeDegrees * PI / 180.0))
            val centre = a
            a = GeoCoordinate(
                centre.latitudeDegrees - deltaLat,
                wrapLongitudeDegrees(centre.longitudeDegrees - deltaLon),
            )
            b = GeoCoordinate(
                centre.latitudeDegrees + deltaLat,
                wrapLongitudeDegrees(centre.longitudeDegrees + deltaLon),
            )
        }
        val type = when (tokens[0].lowercase()) {
            "start" -> TimingGateType.Start
            "split" -> TimingGateType.Split
            else -> TimingGateType.Unknown
        }
        return TimingGate(type, tokens[0], a, b)
    }
}
