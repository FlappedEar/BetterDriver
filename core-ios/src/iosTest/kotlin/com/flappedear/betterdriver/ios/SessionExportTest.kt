/** The iPhone exports a session as Android does: VBO, and VBO with its video for Circuit Tools (FBBD-333). */
class SessionExportTest {
    private val base = NSTemporaryDirectory() + "session-export-test-" + NSUUID().UUIDString
    private val gnss = FakeGnss()

    @AfterTest
    fun cleanUp() {
        NSFileManager.defaultManager.removeItemAtPath(base, null)
    }

    /** A box: 4-byte size, 4-byte type, [body] bytes. */
    private fun box(type: String, body: Int): ByteArray {
        val size = 8 + body
        return byteArrayOf((size shr 24).toByte(), (size shr 16).toByte(), (size shr 8).toByte(), size.toByte()) +
            type.encodeToByteArray() + ByteArray(body)
    }

    private fun write(path: String, bytes: ByteArray) {
        val data = bytes.usePinned { NSData.create(bytes = it.addressOf(0), length = bytes.size.toULong()) }
        data.writeToFile(path, true)
    }

    private fun read(path: String) = NSString.stringWithContentsOfFile(path, NSUTF8StringEncoding, null)

    /** 20 s at 25 Hz with phone video from 4 s: one whole file and one cut off before its end. */
    private fun record(): String {
        val session = LiveSession.start(
            "$base/sessions", "$base/tracks", CircuitList.Empty,
            SessionInfo(gnss.startUtcMillis, channels = GnssChannels.ALL), receiverHasG = false,
        )
        val log = PhoneVideoLog(session)
        NSFileManager.defaultManager.createDirectoryAtPath(log.videoDir, true, null, null)
        write("${log.videoDir}/${log.fileName(1)}", box("ftyp", 12) + box("mdat", 100) + box("moov", 20))
        write("${log.videoDir}/${log.fileName(2)}", box("ftyp", 12) + box("mdat", 100))
        log.started(log.fileName(1), 4_000_000, 60)
        log.started(log.fileName(2), 12_000_000, 60)
        for (n in 0L..500) session.submit(SampleSet(n * 40_000, gnss.fix(n)))
        session.stop()
        return session.id
    }

    @Test
    fun vboWithVideoIsAFolderForCircuitTools() {
        val id = record()
        val export = SessionExport("$base/sessions", "$base/out")
        assertTrue(export.hasVideo(id))
        val folder = export.vboWithVideo(id)
        assertTrue(folder.endsWith("/BetterDriver-$id"))
        val names = NSFileManager.defaultManager.contentsOfDirectoryAtPath(folder, null).orEmpty().map { it.toString() }
        // The file cut off before its end (no moov) would not play: it is left out.
        assertEquals(setOf("BetterDriver-$id.vbo", "BetterDriver-${id}_0001.MP4"), names.toSet())
        val vbo = read("$folder/BetterDriver-$id.vbo")!!
        assertTrue("[avi]\r\nBetterDriver-${id}_\r\nMP4\r\n" in vbo)
        assertTrue("Generated by BetterDriver" in vbo)
        // The data starts at the video: 16 s of the 20 at 25 Hz.
        val rows = vbo.substringAfter("[data]\r\n").trim().lines()
        assertEquals(401, rows.size)
        assertTrue(rows.first().endsWith(" 0001 000000000"))
    }

    @Test
    fun plainVboHasEveryRow() {
        val id = record()
        val path = SessionExport("$base/sessions", "$base/out").vbo(id)
        val vbo = read(path)!!
        assertFalse("[avi]" in vbo)
        assertEquals(501, vbo.substringAfter("[data]\r\n").trim().lines().size)
    }

    @Test
    fun clipsOfTheClipIndexAreExported() {
        // No video events: a camera's clip known only from the session's clip index (clips.json).
        val session = LiveSession.start(
            "$base/sessions", "$base/tracks", CircuitList.Empty,
            SessionInfo(gnss.startUtcMillis, channels = GnssChannels.ALL), receiverHasG = false,
        )
        val videoDir = PhoneVideoLog(session).videoDir
        NSFileManager.defaultManager.createDirectoryAtPath(videoDir, true, null, null)
        write("$videoDir/GX010089.MP4", box("ftyp", 12) + box("mdat", 100) + box("moov", 20))
        val index = """{"version":1,"clips":[{"fileName":"GX010089.MP4","sourceId":"gopro","sessionOffsetUs":2000000,"status":"LOCAL"}]}"""
        write("$videoDir/clips.json", index.encodeToByteArray())
        for (n in 0L..500) session.submit(SampleSet(n * 40_000, gnss.fix(n)))
        session.stop()
        val export = SessionExport("$base/sessions", "$base/out")
        assertTrue(export.hasVideo(session.id))
        val folder = export.vboWithVideo(session.id)
        val names = NSFileManager.defaultManager.contentsOfDirectoryAtPath(folder, null).orEmpty().map { it.toString() }
        assertEquals(setOf("BetterDriver-${session.id}.vbo", "BetterDriver-${session.id}_0001.MP4"), names.toSet())
        // The data starts at the clip, 2 s in.
        assertEquals(451, read("$folder/BetterDriver-${session.id}.vbo")!!.substringAfter("[data]\r\n").trim().lines().size)
    }

    @Test
    fun aSessionWithoutVideoHasNone() {
        val session = LiveSession.start(
            "$base/sessions", "$base/tracks", CircuitList.Empty,
            SessionInfo(gnss.startUtcMillis, channels = GnssChannels.ALL), receiverHasG = false,
        )
        session.submit(SampleSet(0, gnss.fix(0)))
        session.stop()
        assertFalse(SessionExport("$base/sessions", "$base/out").hasVideo(session.id))
    }
}
