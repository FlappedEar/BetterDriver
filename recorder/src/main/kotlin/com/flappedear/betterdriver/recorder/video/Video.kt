package com.flappedear.betterdriver.recorder.video

/**
 * Cameras that record alongside a session (FBBD-21, FBBD-22). Shared by the phone camera and the
 * GoPro sources: both report through [VideoSink], and the recorder logs what they report as
 * session-clock events, so a camera never touches the session files itself.
 */
object CameraIds {
    const val PHONE = "phone"

    /** The single HERO11 of builds before FBBD-105, in sessions they recorded. */
    const val GOPRO_HERO11 = "gopro_hero11"

    /** The single HERO8 of builds before FBBD-105, in sessions they recorded. */
    const val GOPRO_HERO8 = "gopro_hero8"

    /** A GoPro in the equipment list, by its equipment id: any number of them can record with a session (FBBD-105). */
    fun goPro(equipmentId: String): String = "gopro-$equipmentId"
}

/**
 * A camera that records with the session. [start] and [stop] must not throw for camera faults:
 * a fault is reported with [VideoSink.stopped] and [VideoSink.status], and data recording carries on.
 */
interface VideoSource {
    val camera: String
    fun start(sink: VideoSink)
    fun stop()
}

/**
 * Where a [VideoSource] reports. All times are microseconds on the session clock ([nowMicros]).
 * File names are relative to the session's video directory ([VideoFiles.DIR]).
 */
interface VideoSink {
    fun nowMicros(): Long

    /** [file] began; [startMicros] is the session time of its media time 0. */
    fun started(file: String, startMicros: Long)

    /** At session time [atMicros], [file] had recorded [mediaMicros] of media. About once a second. */
    fun synced(file: String, atMicros: Long, mediaMicros: Long)

    /** [file] ended at session time [atMicros]. [reason] is free text, such as "user" or "thermal". */
    fun stopped(file: String, atMicros: Long, reason: String)

    /** Short state for the track screen's status strip, such as "4K · 60" or "Stopped: too hot". */
    fun status(text: String, ok: Boolean)

    /**
     * Android's thermal [status] (PowerManager.THERMAL_STATUS_*) at session time [atMicros], first and
     * on each change, with the [headroom] forecast if known (FBBD-183). Cameras without it never call it.
     */
    fun thermal(atMicros: Long, status: Int, headroom: Float?) = Unit
}

/** Video files of a session live in its directory under [DIR], next to the clip index (clips.json). */
object VideoFiles {
    const val DIR = "video"

    /** Name of the [index]th (1-based) file a camera records live, for example phone_0001.mp4. */
    fun liveName(camera: String, index: Int, extension: String = "mp4") =
        String.format(java.util.Locale.ROOT, "%s_%04d.%s", camera, index, extension)
}

/**
 * The text of video events: space-separated key=value pairs. Values never contain spaces
 * (camera ids and file names are generated by the app; spaces in a reason become underscores).
 */
object VideoEventText {
    const val CAMERA = "camera"
    const val FILE = "file"
    const val MEDIA_US = "media_us"
    const val REASON = "reason"

    fun format(vararg pairs: Pair<String, Any>): String =
        pairs.joinToString(" ") { (k, v) -> "$k=${v.toString().replace(Regex("\\s+"), "_")}" }

    fun parse(text: String): Map<String, String> = text.split(' ')
        .mapNotNull { part ->
            val eq = part.indexOf('=')
            if (eq <= 0) null else part.substring(0, eq) to part.substring(eq + 1)
        }
        .toMap()
}
