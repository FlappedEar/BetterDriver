package com.flappedear.betterdriver.recorder

import com.flappedear.betterdriver.recorder.vbo.VboColumn
import com.flappedear.betterdriver.recorder.vbo.VboDocument
import com.flappedear.betterdriver.recorder.vbo.VboGate
import com.flappedear.betterdriver.recorder.vbo.VboWriter
import java.io.StringWriter
import java.time.Instant
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class VboWriterTest {

    private val gate = VboGate("Start", 5773.46584, 1832.2827, 5773.4688, 1832.20403, "Start / Finish")

    private fun write(avi: String? = "session_", gates: Boolean = true): String {
        val sw = StringWriter()
        val doc = VboDocument(
            created = Instant.parse("2026-10-11T09:02:23Z"),
            columns = listOf(
                VboColumn("satellites", "sats", "", VboWriter::sats),
                VboColumn("time", "time", "", VboWriter::time),
                VboColumn("latitude", "lat", "", VboWriter::latitude),
                VboColumn("longitude", "long", "", VboWriter::longitude),
                VboColumn("velocity kmh", "velocity", "", VboWriter::velocity),
                VboColumn("heading", "heading", "", VboWriter::heading),
                VboColumn("height", "height", "", VboWriter::height),
                VboColumn("lateral_g", "lateral_g", "g", VboWriter.decimal(3)),
                VboColumn("no_unit", "no_unit", "", VboWriter.decimal(1)),
            ),
            comments = listOf("Generated by test"),
            gates = if (gates) listOf(gate) else emptyList(),
            aviBaseName = avi,
            rows = sequenceOf(
                doubleArrayOf(7.0, 50_528_800.0, 30.538262, -96.223669, 30.725, 223.24, 43.7, 0.25, 1.0),
                doubleArrayOf(7.0, 50_528_840.0, 30.538263, -96.223670, 30.8, 223.3, 43.7, -0.25, 2.0),
            ),
        )
        VboWriter(sw).write(doc)
        return sw.toString()
    }

    @Test
    fun `sections come in Racelogic order`() {
        val p = VboValidator.validate(write())
        assertEquals(
            listOf("[header]", "[channel units]", "[comments]", "[laptiming]", "[avi]", "[column names]", "[data]"),
            p.sections,
        )
        assertEquals("File created on 11/10/2026 @ 09:02:23", p.firstLine)
    }

    @Test
    fun `optional sections are left out when empty`() {
        val p = VboValidator.validate(write(avi = null, gates = false))
        assertEquals(listOf("[header]", "[channel units]", "[comments]", "[column names]", "[data]"), p.sections)
    }

    @Test
    fun `units has one line per non-standard channel, blank allowed`() {
        val p = VboValidator.validate(write())
        assertEquals(listOf("g", ""), p.units)
        assertEquals(9, p.header.size)
    }

    @Test
    fun `time is hhmmss with three decimals and wraps at midnight`() {
        assertEquals("140208.800", VboWriter.time(50_528_800.0))
        assertEquals("000000.040", VboWriter.time(86_400_040.0))
        assertEquals("235959.999", VboWriter.time(86_399_999.0))
        // An epoch timestamp works too: only the time of day is written.
        assertEquals("090223.000", VboWriter.time(Instant.parse("2026-10-11T09:02:23Z").toEpochMilli().toDouble()))
    }

    @Test
    fun `positions are minutes with longitude positive west`() {
        assertEquals("+01832.29572", VboWriter.latitude(30.538262))
        assertEquals("+05773.42014", VboWriter.longitude(-96.223669))
        assertEquals("-01260.00000", VboWriter.longitude(21.0))
        assertEquals("-03120.00000", VboWriter.latitude(-52.0))
    }

    @Test
    fun `fixed-width standard fields`() {
        assertEquals("007", VboWriter.sats(7.0))
        assertEquals("030.725", VboWriter.velocity(30.725))
        assertEquals("223.24", VboWriter.heading(223.24))
        assertEquals("000.00", VboWriter.heading(360.0))
        assertEquals("+00043.70", VboWriter.height(43.7))
        assertEquals("-00001.50", VboWriter.height(-1.5))
    }

    @Test
    fun `data rows and laptiming line`() {
        val text = write()
        val row = "007 140208.800 +01832.29572 +05773.42014 030.725 223.24 +00043.70 0.250 1.0"
        assertTrue(text.contains("\r\n$row\r\n"), text)
        val line = "Start   +5773.465840 +1832.282700 +5773.468800 +1832.204030 \u00AC Start / Finish"
        assertTrue(text.contains("\r\n$line\r\n"), text)
    }
}
